#!/usr/bin/env node
// Builds src/lib/geo/zip-data.generated.ts from the public GeoNames US postal-code file.
//
//   curl -O https://download.geonames.org/export/zip/US.zip && unzip US.zip US.txt
//   node scripts/build-zip-data.mjs path/to/US.txt
//
// Output: one gzip+base64 string of "zip|city|ST|lat|lon" rows (3-decimal coordinates, about
// 100 m). The module is server-only: never import it from a client component, or it ships to
// the browser. Data © GeoNames (https://www.geonames.org), licensed CC BY 4.0
// (https://creativecommons.org/licenses/by/4.0/). Keep the credit wherever the data is shown.

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-zip-data.mjs path/to/US.txt");
  process.exit(1);
}

const rows = new Map();
for (const line of fs.readFileSync(input, "utf8").split(/\r?\n/)) {
  if (!line) continue;
  // country, postal code, place name, state name, state code, county, county code, , , lat, lon, accuracy
  const f = line.split("\t");
  const zip = f[1];
  const lat = Number(f[9]);
  const lon = Number(f[10]);
  if (!/^\d{5}$/.test(zip) || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  if (rows.has(zip)) continue;
  const city = (f[2] ?? "").replace(/[|\n\r]/g, " ").trim();
  const state = /^[A-Z]{2}$/.test(f[4] ?? "") ? f[4] : "";
  rows.set(zip, `${zip}|${city}|${state}|${lat.toFixed(3)}|${lon.toFixed(3)}`);
}

const text = [...rows.values()].sort().join("\n");
const gz = zlib.gzipSync(Buffer.from(text, "utf8"), { level: 9 }).toString("base64");

const out = `// GENERATED by scripts/build-zip-data.mjs. Do not edit by hand.
// ZIP code, place name, state and approximate centroid for ${rows.size} US ZIP codes.
// Data © GeoNames (https://www.geonames.org), licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Server-only: importing this from a client component would ship it to the browser.
export const ZIP_DATA_ROW_COUNT = ${rows.size};
export const ZIP_DATA_GZ_BASE64 =
  "${gz}";
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "geo", "zip-data.generated.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${rows.size} ZIP codes (${(out.length / 1024).toFixed(0)} KB) to ${path.relative(process.cwd(), target)}`);
