#!/usr/bin/env node
// Builds src/lib/geo/zip-demand-data.generated.ts from U.S. Census Bureau ACS 5-year tables.
//
// Source (public domain): American Community Survey 2019-2023 5-year estimates, table-based
// summary files, ZIP Code Tabulation Areas (geography 860):
//   https://www2.census.gov/programs-surveys/acs/summary_file/2023/table-based-SF/data/5YRData/
//     acsdt5y2023-b01003.dat   total population
//     acsdt5y2023-b25003.dat   occupied housing units (households)
//     acsdt5y2023-b07013.dat   geographical mobility in the past year by tenure
//
//   node scripts/build-zip-demand-data.mjs path/to/folder-with-the-three-.dat-files
//
// Output rows: "zip|population|households|ownerMovers|allMovers" where the movers columns are PEOPLE
// living in the ZIP code who moved into their current home within the past year (owner-occupied
// homes, and all homes). src/lib/zip-demand.ts turns these into monthly household estimates.
// Server-only module: never import it from a client component.

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/build-zip-demand-data.mjs path/to/acs-folder");
  process.exit(1);
}

const ZCTA = "860Z200US";

/** Reads one table and returns Map<zip, Record<columnName, number>> for the estimate columns asked for. */
function readTable(file, columns) {
  const lines = fs.readFileSync(path.join(dir, file), "utf8").split(/\r?\n/);
  const header = lines[0].split("|");
  const at = columns.map((c) => {
    const i = header.indexOf(c);
    if (i < 0) throw new Error(`${file} has no column ${c}`);
    return i;
  });
  const out = new Map();
  for (const line of lines) {
    if (!line.startsWith(ZCTA)) continue;
    const f = line.split("|");
    const zip = f[0].slice(ZCTA.length);
    if (!/^\d{5}$/.test(zip)) continue;
    const row = {};
    columns.forEach((c, k) => {
      const n = Number(f[at[k]]);
      row[c] = Number.isFinite(n) && n >= 0 ? n : 0;
    });
    out.set(zip, row);
  }
  return out;
}

const population = readTable("b01003.dat", ["B01003_E001"]);
const households = readTable("b25003.dat", ["B25003_E001"]);
// E002 people in owner-occupied homes, E005 of those in the same house a year ago;
// E001 everyone in households, E004 of those in the same house a year ago.
const mobility = readTable("b07013.dat", ["B07013_E001", "B07013_E002", "B07013_E004", "B07013_E005"]);

const rows = [];
for (const [zip, pop] of population) {
  const hh = households.get(zip)?.B25003_E001 ?? 0;
  const m = mobility.get(zip);
  const ownerMovers = m ? Math.max(0, m.B07013_E002 - m.B07013_E005) : 0;
  const allMovers = m ? Math.max(0, m.B07013_E001 - m.B07013_E004) : 0;
  rows.push(`${zip}|${pop.B01003_E001}|${hh}|${ownerMovers}|${allMovers}`);
}
rows.sort();

const gz = zlib.gzipSync(Buffer.from(rows.join("\n"), "utf8"), { level: 9 }).toString("base64");
const out = `// GENERATED by scripts/build-zip-demand-data.mjs. Do not edit by hand.
// Population, households and past-year movers for ${rows.length} ZIP Code Tabulation Areas.
// Source: U.S. Census Bureau, American Community Survey 2019-2023 5-year estimates (tables B01003,
// B25003, B07013). Public domain. Survey estimates carry sampling error, most of all in small ZIP codes.
// Server-only: importing this from a client component would ship it to the browser.
export const ZIP_DEMAND_ROW_COUNT = ${rows.length};
export const ZIP_DEMAND_VINTAGE = "2019-2023";
export const ZIP_DEMAND_GZ_BASE64 =
  "${gz}";
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "geo", "zip-demand-data.generated.ts");
fs.writeFileSync(target, out);
console.log(`Wrote ${rows.length} ZIP codes (${(out.length / 1024).toFixed(0)} KB) to ${path.relative(process.cwd(), target)}`);
